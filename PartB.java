public class PartB {
    static void main() {

        // Task 5
        for (int i = 1; i <= 5; i++){
            for (int j = 0; j < i; j++){
                System.out.print("*");
            }
            System.out.println();
        }
        System.out.println();



        // Task 6
        for (int i = 5; i >= 0; i--){
            for (int j = 0; j < i; j++){
                System.out.print("*");
            }
            System.out.println();
        }




        // Task 7
        for (int i = 0; i < 5; i++ ){
            for (int j = 0; j < 5; j++ ){
                System.out.print("*");
            }
            System.out.println();
        }

    }
}
